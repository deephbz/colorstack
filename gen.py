def lexical_path(value: str | Path) -> Path:
    """Normalize `.`/`..` without dereferencing a single filesystem link."""
    return Path(os.path.abspath(os.path.expanduser(os.fspath(value))))


def assert_no_symlink_ancestors(path: Path) -> None:
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        try:
            mode = current.lstat().st_mode
        except FileNotFoundError:
            return
        if stat.S_ISLNK(mode):
            raise ValueError(f"output root or ancestor is a symlink: {current}")


def output_root(value: str | Path | None) -> Path:
    """Validate an explicit, caller-owned Colorstack output bundle root.

    Colorstack never discovers application config paths or HOME targets. The
    caller may choose any path outside this source checkout; `render` requires
    it to be fresh and `switch.py` only replaces a bundle it previously made.
    """
    if value is None:
        raise ValueError("--output-root is required; colorstack never chooses a destination")
    root = lexical_path(value)
    assert_no_symlink_ancestors(root)
    if root == REPO or REPO in root.parents:
        raise ValueError("--output-root may not be inside the Colorstack source checkout")
    if root.exists() and not root.is_dir():
        raise ValueError("--output-root must be a directory when it exists")
    return root


def mkdir_no_symlink(path: Path) -> None:
    assert_no_symlink_ancestors(path)
    path.mkdir(parents=True, exist_ok=True)
    assert_no_symlink_ancestors(path)
    if not path.is_dir():
        raise ValueError(f"output directory is not a directory: {path}")


def write_new(root: Path, relative: Path, data: bytes) -> Path:
    """Create one new regular file without following an output-path symlink."""
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"invalid controlled output path: {relative}")
    parent = root / relative.parent
    mkdir_no_symlink(parent)
    destination = root / relative
    try:
        fd = os.open(destination, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
    except FileExistsError:
        raise ValueError(f"controlled output already exists; use a fresh output root: {destination}") from None
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
    except Exception:
        destination.unlink(missing_ok=True)
        raise
    return destination


def parse_keys(values: list[str] | None) -> tuple[str, ...]:
    requested = tuple(dict.fromkeys(key for value in values or [] for key in value.split(",") if key))
    keys = requested or tuple(OUTPUT_BY_KEY)
    unknown = sorted(set(keys) - set(OUTPUT_BY_KEY))
    if unknown:
        raise ValueError(f"unknown output key(s): {', '.join(unknown)}")
    return keys


def render_all(th: T.Theme, keys: tuple[str, ...] | None = None) -> dict[str, str]:
    keys = keys or tuple(OUTPUT_BY_KEY)
    return {key: EMITTERS[key](th) for key in keys}


def output_manifest(th: T.Theme, scheme: str, ink: float, body: dict[str, str]) -> dict:
    return {
        "schema_version": 1,
        "generator": "colorstack",
        "scheme": scheme,
        "ink_contrast": ink,
        "outputs": {
            key: {
                "path": OUTPUT_BY_KEY[key].relative_path.as_posix(),
                "sha256": hashlib.sha256(text.encode()).hexdigest(),
                "ownership": OUTPUT_BY_KEY[key].ownership.value,
            }
            for key, text in sorted(body.items())
        },
    }


def emit(th: T.Theme, scheme: str, ink: float, root: Path, keys: tuple[str, ...], dry: bool) -> tuple[dict, list[str]]:
    """Render only declared keys into a caller-owned root, never into source."""
    body = render_all(th, keys)
    manifest = output_manifest(th, scheme, ink, body)
    log = [f"  output root  {root}"]
    if not dry:
        mkdir_no_symlink(root)
    for key, text in sorted(body.items()):
        destination = root / OUTPUT_BY_KEY[key].relative_path
        if dry:
            log.append(f"  would write   {key} -> {destination}")
            continue
        write_new(root, OUTPUT_BY_KEY[key].relative_path, text.encode())
        log.append(f"  write         {key} -> {destination}")
    if dry:
        log.append(f"  would write   manifest -> {root / MANIFEST_NAME}")
    else:
        write_new(root, Path(MANIFEST_NAME), (json.dumps(manifest, sort_keys=True, separators=(",", ":")) + "\n").encode())
        log.append(f"  write         manifest -> {root / MANIFEST_NAME}")
    return manifest, log


def compare(floor: float) -> None:
    """Every authored palette, ranked -- in TWO tables, by polarity.

    Not cosmetic. Fidelity is degenerate on dark surfaces (contrast is nearly
    free below, so a dozen schemes tie at 0.00), so a single fidelity-ordered
    table floats every dark theme to the top on a metric that did not measure
    them. Each polarity gets the rank key its failure mode deserves: fidelity
    for light, glare then spread for dark. See docs/ontology.md.
    """
    from colorspace import CEILINGS, lstar

    def key_of(p):
        return p.key or p.name.split()[0].lower()

    light = [p for p in P.ALL if not p.is_dark]
    dark = [p for p in P.ALL if p.is_dark]

    print(f"\n  LIGHT -- ranked by fidelity at floor {floor}\n")
    print(
        f"  {'key':22s}{'scheme':24s}{'bg':10s}{'L*':>6s}{'→white':>8s}"
        f"{'warm':>7s}{'moved':>7s}{'fidel':>8s}{'ink':>8s}  struct"
    )
    for p in sorted(light, key=lambda q: (q.fidelity(floor), q.step_to_white)):
        moved = f"{p.accents_moved(floor)}/{len(p.accents)}"
        print(
            f"  {key_of(p):22s}{p.name:24s}{p.bg:10s}{lstar(p.bg):6.1f}"
            f"{p.step_to_white:8.1f}{p.warmth:7.1f}{moved:>7s}"
            f"{p.fidelity(floor):8.2f}{p.ink_contrast:7.1f}:1  "
            f"{'ok' if p.structure_ok() else 'no'}"
        )

    # Dark is deliberately NOT ranked. Fidelity ties at 0.00, and so does
    # glare once the surface is dark enough -- ranking on what is left means
    # ranking on the tiebreak, which is spread, which rewards saturation. So
    # the numbers are used the only way they are honest here: to rule schemes
    # OUT. What survives is a shortlist for the eye, not an ordering.
    print("\n  DARK -- flags, not a ranking: these numbers exclude, they do not order\n")
    print(
        f"  {'key':22s}{'scheme':24s}{'bg':10s}{'L*':>6s}{'warm':>7s}"
        f"{'spread':>8s}{'ink':>8s}  flags"
    )
    for p in sorted(dark, key=lambda q: (len(_dark_flags(q, floor)), -lstar(q.bg))):
        flags = _dark_flags(p, floor)
        print(
            f"  {key_of(p):22s}{p.name:24s}{p.bg:10s}{lstar(p.bg):6.1f}"
            f"{p.warmth:7.1f}{p.accent_spread():8.1f}{p.ink_contrast:7.1f}:1  "
            f"{', '.join(flags) if flags else 'clean'}"
        )
    print(
        "\n  halation = surface below L* 10, where light glyphs bloom hardest\n"
        "  floor    = accents under 4.5:1, which repair will have to invent\n"
        f"  glare    = accents over {CEILINGS['accent']}:1, which soften pulls back\n"
    )


def _dark_flags(p, floor: float) -> list[str]:
    from colorspace import lstar

    out = []
    if lstar(p.bg) < 10:
        out.append("halation")
    if p.accents_moved(floor):
        out.append(f"floor({p.accents_moved(floor)})")
    if p.accents_glaring():
        out.append(f"glare({p.accents_glaring()})")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Render Colorstack only into a caller-provided controlled root")
    ap.add_argument("scheme", nargs="?")
    ap.add_argument("--output-root", help="controlled root receiving generated outputs and manifest")
    ap.add_argument("--key", action="append", help="output key (repeat or comma-separate); default is every generated/region key")
    ap.add_argument("--dry-run", action="store_true", help="name writes under --output-root without creating them")
    ap.add_argument("--list", action="store_true", help="list typed layers relative to --output-root; writes nothing")
    ap.add_argument("--compare", action="store_true", help="rank every palette; writes nothing")
    ap.add_argument("--floor", type=float, default=4.5, help="floor for --compare")
    ap.add_argument("--ink", type=float, default=10.0, help="body text contrast target")
    a = ap.parse_args()

    if a.compare:
        if a.output_root or a.scheme or a.key or a.dry_run or a.list:
            ap.error("--compare is inspection-only and accepts no output contract")
        compare(a.floor)
        return

    try:
        root = output_root(a.output_root)
        keys = parse_keys(a.key)
    except ValueError as e:
        ap.error(str(e))

    if a.list:
        if a.scheme:
            ap.error("--list does not accept a scheme")
        print(f"  output root  {root}")
        for layer in LAYERS:
            path = root / OUTPUT_BY_KEY[layer.output_key].relative_path if layer.output_key else Path("(authored include; no output)")
            print(f"  {layer.ownership.value:10s} {layer.key:18s} {path}")
        return

    if not a.scheme:
        ap.error("scheme is required when rendering")
    pal = P.BY_KEY.get(a.scheme)
    if pal is None:
        ap.error(f"unknown scheme {a.scheme!r}; have: {', '.join(P.BY_KEY)}")

    th = T.build(pal, ink_contrast=a.ink)
    print(f"\n{th.name}  bg {th.bg}  fg {th.fg}  ink {contrast(th.fg, th.bg):.1f}")
    problems = th.check()
    if problems:
        print("  FAILS ITS OWN FLOORS:")
        for p in problems:
            print(f"    {p}")
        raise SystemExit(1)
    print("  all floors met\n")
    _, log = emit(th, a.scheme, a.ink, root, keys, a.dry_run)
    for line in log:
        print(line)
    print()


if __name__ == "__main__":
    main()
