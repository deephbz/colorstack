class Ownership(str, Enum):
    """Who owns a layer's bytes; this is deliberately not a free-form string."""

    GENERATED = "GENERATED"
    INCLUDE = "INCLUDE"
    REGION = "REGION"


@dataclass(frozen=True)
class Layer:
    key: str
    ownership: Ownership
    output_key: str | None = None


@dataclass(frozen=True)
class Output:
    key: str
    ownership: Ownership
    emitter: str

    @property
    def relative_path(self) -> Path:
        return Path("outputs") / self.key


