def ghostty(th: T.Theme) -> str:
    L = [f"# {BANNER}", f"# {th.name}", ""]
    for i, c in enumerate(th.ansi):
        L.append(f"palette = {i}={c}")
    L += [
        "",
        f"background = {th.bg}",
        f"foreground = {th.fg}",
        f"cursor-color = {th.cursor}",
        f"cursor-text = {th.bg}",
        f"selection-background = {th.selection_bg}",
        f"selection-foreground = {th.selection_fg}",
        "",
    ]
    if th.is_light:
        L += [
            "# Light surfaces thin dark glyphs by edge bleed; compensate.",
            "# Deliberately NOT set on dark themes, where the bleed runs the",
            "# other way -- light-on-dark glyphs already bloom, and thickening",
            "# them makes the halation this stack tries to limit worse.",
            "font-thicken = true",
            "font-thicken-strength = 40",
        ]
    else:
        L += [
            "# No font-thicken: light-on-dark glyphs bloom on their own.",
            "font-thicken = false",
        ]
    L += [
        "",
        "# never set `theme`: it silently owns every key this file omits",
    ]
    return "\n".join(L) + "\n"


