def bat_theme(th: T.Theme) -> str:
    a = th.ansi

    def d(name, scope, fg=None, style=None):
        body = f"\t\t\t<key>name</key>\n\t\t\t<string>{name}</string>\n"
        body += f"\t\t\t<key>scope</key>\n\t\t\t<string>{scope}</string>\n"
        body += "\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
        if fg:
            body += f"\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>{fg}</string>\n"
        if style:
            body += f"\t\t\t\t<key>fontStyle</key>\n\t\t\t\t<string>{style}</string>\n"
        body += "\t\t\t</dict>"
        return f"\t\t<dict>\n{body}\n\t\t</dict>"

    rules = [
        d("Comment", "comment", th.dim, "italic"),
        d("String", "string", a[2]),
        d("Number", "constant.numeric", a[5]),
        d("Constant", "constant.language, constant.character", a[5]),
        d("Keyword", "keyword, storage.type, storage.modifier", a[4]),
        d("Operator", "keyword.operator", a[6]),
        d("Function", "entity.name.function, support.function", a[3]),
        d("Class", "entity.name.class, entity.name.type, support.class", a[6]),
        d("Variable", "variable, variable.parameter", th.fg),
        d("Tag", "entity.name.tag", a[1]),
        d("Attribute", "entity.other.attribute-name", a[3]),
        d("Invalid", "invalid", a[1], "bold"),
        d("Diff added", "markup.inserted", a[2]),
        d("Diff removed", "markup.deleted", a[1]),
        d("Diff changed", "markup.changed", a[3]),
        d("Heading", "markup.heading", a[4], "bold"),
        d("Link", "markup.underline.link", a[6], "underline"),
    ]
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
        '<plist version="1.0">\n<dict>\n'
        f"\t<key>name</key>\n\t<string>colorstack</string>\n"
        f"\t<!-- {BANNER} -->\n"
        "\t<key>settings</key>\n\t<array>\n"
        "\t\t<dict>\n\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
        f"\t\t\t\t<key>background</key>\n\t\t\t\t<string>{th.bg}</string>\n"
        f"\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>{th.fg}</string>\n"
        f"\t\t\t\t<key>caret</key>\n\t\t\t\t<string>{th.cursor}</string>\n"
        f"\t\t\t\t<key>selection</key>\n\t\t\t\t<string>{th.selection_bg}</string>\n"
        f"\t\t\t\t<key>lineHighlight</key>\n\t\t\t\t<string>{th.bg_soft}</string>\n"
        "\t\t\t</dict>\n\t\t</dict>\n"
        + "\n".join(rules)
        + "\n\t</array>\n"
        "</dict>\n</plist>\n"
    )


