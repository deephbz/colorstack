def herdr(th: T.Theme) -> str:
    """herdr's [theme.custom] tokens, derived from the palette.

    Two traps, both found the hard way:
      * the section is [theme], NOT [ui.theme]. herdr silently ignores unknown
        keys, so a misplaced section applies nothing and reports no error --
        which looks exactly like "the theme did not help".
      * the token names are Catppuccin's, where on a LIGHT theme surface0/1 sit
        DARKER than the base, not lighter. Getting that backwards inverts the
        panel depth cues.
    """
    a = th.ansi
    from colorspace import FLOORS, mix_oklab, repair_on

    surface0 = mix_oklab(th.bg, th.fg, 0.10)
    surface1 = mix_oklab(th.bg, th.fg, 0.18)
    surface_dim = mix_oklab(th.bg, th.fg, 0.06)
    # Herdr draws these on its own tiers, so they clear floors there too.
    tiers = (th.bg, surface0, surface1, surface_dim)
    overlay0 = repair_on(mix_oklab(th.bg, th.fg, 0.45), tiers, FLOORS["accent"])
    overlay1 = repair_on(mix_oklab(th.bg, th.fg, 0.60), tiers, FLOORS["text"])
    peach = repair_on(th.source.accents.get("orange", a[3]), tiers, FLOORS["text"])
    subtext0 = repair_on(th.dim, tiers, FLOORS["text"])

    return "\n".join([
        f"# {BANNER}",
        f"# {th.name}",
        "",
        "[theme]",
        "# A fixed substrate, deliberately NOT tied to the palette: herdr needs",
        "# a name it recognises, and every token that matters is overridden",
        "# below. Its only job is to catch tokens [theme.custom] does not name.",
        'name = "kanagawa-lotus"',
        "auto_switch = false",
        "",
        "[theme.custom]",
        f'panel_bg = "{th.bg}"',
        f'surface0 = "{surface0}"',
        f'surface1 = "{surface1}"',
        f'surface_dim = "{surface_dim}"',
        f'overlay0 = "{overlay0}"',
        f'overlay1 = "{overlay1}"',
        f'text = "{th.fg}"',
        # agent labels are read, not decoration: text floor, not accent floor
        f'subtext0 = "{subtext0}"',
        f'accent = "{peach}"',
        f'red = "{a[1]}"',
        f'green = "{a[2]}"',
        f'yellow = "{a[3]}"',
        f'blue = "{a[4]}"',
        f'mauve = "{a[5]}"',
        f'teal = "{a[6]}"',
        f'peach = "{peach}"',
    ]) + "\n"


