#!/usr/bin/env python3
"""Render Colorstack's declared palette into a caller-provided controlled root.

    python3 gen.py --list --output-root ./colorstack-output
    python3 gen.py modus --output-root ./colorstack-output --dry-run
    python3 gen.py modus --output-root ./colorstack-output

The root is mandatory for every output-facing command. Rendering never infers a
repository destination, accepts only a caller-supplied root outside this source
checkout, rejects symlinked ancestors, and never links or applies live HOME
state. Successful emission writes a machine-operable
`.colorstack-manifest.json` whose named keys, relative paths, ownership modes,
and SHA-256 digests are the builder contract.

`GENERATED` files are wholly Colorstack-owned; `INCLUDE` files are hand-kept and
produce no Colorstack bytes; `REGION` keys are payloads spliced only by the
staging builder into typed marker contracts. Design: docs/ontology.md.
"""

